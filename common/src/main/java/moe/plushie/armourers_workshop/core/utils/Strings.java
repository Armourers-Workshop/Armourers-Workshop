package moe.plushie.armourers_workshop.core.utils;

public class Strings {

    public static boolean isEmpty(String value) {
        return org.apache.logging.log4j.util.Strings.isEmpty(value);
    }

    public static boolean isNotEmpty(String value) {
        return org.apache.logging.log4j.util.Strings.isNotEmpty(value);
    }

    public static boolean isBlank(String value) {
        return org.apache.logging.log4j.util.Strings.isBlank(value);
    }

    public static boolean isNotBlank(String value) {
        return org.apache.logging.log4j.util.Strings.isNotBlank(value);
    }
}
